import { describe, expect, it } from 'vitest';

import { NB_HYPHEN as H, NBSP as _, typograph } from './typograph';

describe('typograph', () => {
  it('ставит неразрывный пробел после предлога', () => {
    expect(typograph('Запах известняка после дождя в саду')).toBe(
      `Запах известняка после дождя в${_}саду`,
    );
  });

  it('обрабатывает предлог в начале строки и с заглавной буквы', () => {
    expect(typograph('В бутике можно попробовать')).toBe(`В${_}бутике можно попробовать`);
  });

  it('обрабатывает подряд идущие короткие слова', () => {
    expect(typograph('камень и в воде')).toBe(`камень и${_}в${_}воде`);
  });

  it('связывает трёхбуквенные предлоги из списка', () => {
    expect(typograph('ароматы для дома без спешки')).toBe(`ароматы для${_}дома без${_}спешки`);
  });

  it('не трогает обычные длинные слова', () => {
    expect(typograph('медленно выпускаем немного')).toBe('медленно выпускаем немного');
  });

  it('связывает короткое слово после открывающей кавычки и скобки', () => {
    expect(typograph('«На закате» (с ирисом)')).toBe(`«На${_}закате» (с${_}ирисом)`);
  });

  it('не отрывает частицы от предыдущего слова', () => {
    expect(typograph('так же как бы между прочим')).toBe(`так${_}же как${_}бы между прочим`);
  });

  it('ставит неразрывный пробел перед тире', () => {
    expect(typograph('Каждый аромат — небольшая архитектура')).toBe(
      `Каждый аромат${_}— небольшая архитектура`,
    );
  });

  it('связывает число с единицей измерения', () => {
    expect(typograph('Флакон 50 мл, стойкость 8 ч, скидок нет')).toBe(
      `Флакон 50${_}мл, стойкость 8${_}ч, скидок нет`,
    );
  });

  it('не связывает число со словом, которое только начинается как единица', () => {
    expect(typograph('3 минуты')).toBe('3 минуты');
  });

  it('связывает знак номера с числом', () => {
    expect(typograph('Образец № 03')).toBe(`Образец №${_}03`);
  });

  it('ставит неразрывный дефис в коротких составных словах', () => {
    expect(typograph('из-за дождя, кто-то по-русски')).toBe(
      `из${H}за дождя, кто${H}то по${H}русски`,
    );
  });

  it('ставит неразрывный дефис и после связанного короткого слова', () => {
    expect(typograph('а из-за')).toBe(`а${_}из${H}за`);
  });

  it('не трогает длинные составные слова', () => {
    expect(typograph('светло-серый')).toBe('светло-серый');
  });

  it('не трогает ссылки и почту', () => {
    const text = 'пишите на hi-there@nisha.ru или на https://nisha.ru/is-it';
    expect(typograph(text)).toBe(
      `пишите на${_}hi-there@nisha.ru или${_}на${_}https://nisha.ru/is-it`,
    );
  });

  it('не переносит неразрывный пробел через перевод строки', () => {
    expect(typograph('в\nсаду')).toBe('в\nсаду');
  });

  it('идемпотентен', () => {
    const once = typograph('Мы искали запах камня, который ещё помнит огонь — и из-за этого 3 мл');
    expect(typograph(once)).toBe(once);
  });

  it('возвращает пустую строку как есть', () => {
    expect(typograph('')).toBe('');
  });
});
